#!/usr/bin/env node
// ============================================================================
// Regenerate src/content/blog/posts/all.ts — a STATIC barrel of every EN blog
// post module.
// ----------------------------------------------------------------------------
// Why a barrel at all: src/content/blog/index.ts loads posts with
// `import.meta.glob`, which only exists in Vite. Cloudflare Pages Functions are
// bundled by wrangler/esbuild, so the SSR renderer cannot use it — without a
// static import list the bot path has no access to post bodies, which is
// exactly why every EN post used to serve Googlebot ~0.9 KB of <main>.
//
// The SPA keeps using the glob loader (lazy, one chunk per post), so this
// barrel does not affect the client bundle — nothing under src/ imports it.
//
// Run after adding or removing a post:  node scripts/gen-blog-barrel.mjs
// src/content/blog/__tests__/blog-barrel.test.ts fails if it drifts.
// ============================================================================

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const postsDir = resolve(here, "..", "src", "content", "blog", "posts");
const outFile = resolve(postsDir, "all.ts");

const slugs = readdirSync(postsDir)
  .filter((f) => f.endsWith(".ts") && f !== "all.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const body = `// AUTO-GENERATED by scripts/gen-blog-barrel.mjs — do not edit by hand.
// Static barrel of every EN blog post, for consumers that cannot use Vite's
// import.meta.glob (Cloudflare Pages Functions / the SSR bot path).
//
// Loaders, not values, on purpose: _middleware.ts runs for EVERY request, and
// a static import list would construct all ${slugs.length} post objects at worker
// startup. esbuild wraps dynamically-imported modules in lazy __esm() inits, so
// a request only pays for the one post it renders.
//
// Regenerate:  node scripts/gen-blog-barrel.mjs
import type { BlogPost } from "../types";

export const blogPostLoaders: Record<string, () => Promise<{ default: BlogPost }>> = {
${slugs.map((s) => `  "${s}": () => import("./${s}"),`).join("\n")}
};

export const blogPostSlugs = Object.keys(blogPostLoaders);

/** Load one post's module. Returns undefined for an unknown slug. */
export async function loadBlogPost(slug: string): Promise<BlogPost | undefined> {
  const loader = blogPostLoaders[slug];
  if (!loader) return undefined;
  return (await loader()).default;
}
`;

writeFileSync(outFile, body);
console.log(`gen-blog-barrel: wrote ${slugs.length} posts to ${outFile}`);
