#!/usr/bin/env node
// ============================================================================
// Regenerate src/content/blog/image-dims.ts — intrinsic width/height for every
// blog image under public/images/blog.
// ----------------------------------------------------------------------------
// Two things needed these numbers and neither had them:
//
//   1. The SSR bot path rendered ZERO <img> tags (audit 2026-08-25, H1:
//      132/135 crawled pages had none). A hero image can only be indexed by
//      Google Images / surface in Discover if it is in the HTML the crawler
//      actually gets, and it should carry real dimensions there.
//   2. The SPA hero (src/pages/BlogPost.tsx) hardcoded width={1200}
//      height={630} for every post while the real assets run 1536x1024,
//      1600x900, 1024x1536... With `height: auto` the browser derives the
//      pre-load placeholder from those attributes, so a 1536x1024 hero
//      reserved a 1.905 box and then resolved into a 1.5 one — a layout shift
//      on the highest-yield content on the site.
//
// Dimensions come from the WebP headers themselves, so they cannot drift from
// the files. Everything in public/images/blog is .webp today; the parser
// throws on anything else rather than guessing.
//
// Run after adding or replacing a blog image:  node scripts/gen-blog-image-dims.mjs
// src/content/blog/__tests__/blog-image-dims.test.ts fails if it drifts.
// ============================================================================

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const imagesDir = resolve(here, "..", "public", "images", "blog");
const outFile = resolve(here, "..", "src", "content", "blog", "image-dims.ts");

/**
 * Intrinsic size from a WebP header. Covers the three bitstream flavours the
 * encoders in this repo emit: lossy (VP8 ), lossless (VP8L) and extended
 * (VP8X, which is what any animated/alpha/ICC file uses).
 */
function webpSize(buf, label) {
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WEBP") {
    throw new Error(`${label}: not a WebP file`);
  }
  const fourcc = buf.toString("ascii", 12, 16);
  if (fourcc === "VP8 ") {
    return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  }
  if (fourcc === "VP8L") {
    const bits = buf.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1];
  }
  if (fourcc === "VP8X") {
    const read24 = (o) => buf[o] | (buf[o + 1] << 8) | (buf[o + 2] << 16);
    return [read24(24) + 1, read24(27) + 1];
  }
  throw new Error(`${label}: unknown WebP chunk "${fourcc}"`);
}

const files = readdirSync(imagesDir).filter((f) => !f.startsWith("."));
const nonWebp = files.filter((f) => !f.endsWith(".webp"));
if (nonWebp.length) {
  console.error(`Non-WebP files in public/images/blog: ${nonWebp.join(", ")}`);
  console.error("Teach webpSize() that format before adding it to the map.");
  process.exit(1);
}

const entries = files.sort().map((f) => {
  const [w, h] = webpSize(readFileSync(resolve(imagesDir, f)), f);
  return `  "/images/blog/${f}": [${w}, ${h}],`;
});

const body = `// AUTO-GENERATED by scripts/gen-blog-image-dims.mjs — do not edit by hand.
// Intrinsic [width, height] of every asset in public/images/blog, read from
// the WebP headers. Consumed by the SPA hero (src/pages/BlogPost.tsx,
// src/pages/ViBlogPost.tsx) and by the SSR bot path
// (functions/_lib/render/blog-body.ts, functions/_lib/render/blog.ts) so both
// declare the real aspect ratio instead of a guessed 1200x630.
//
// Regenerate:  node scripts/gen-blog-image-dims.mjs

export const BLOG_IMAGE_DIMS: Record<string, readonly [number, number]> = {
${entries.join("\n")}
};

/**
 * [width, height] for a blog image path, or undefined when the asset is not
 * one of ours (Supabase Storage covers, Google Drive links, absolute URLs on
 * other hosts). Callers omit the attributes in that case rather than guess —
 * a wrong aspect ratio shifts the page harder than no aspect ratio at all.
 */
export function blogImageDims(
  src: string | null | undefined,
): readonly [number, number] | undefined {
  if (!src) return undefined;
  const path = src.split("?")[0].replace(/^https?:\\/\\/[^/]+/, "");
  return BLOG_IMAGE_DIMS[path];
}
`;

writeFileSync(outFile, body);
console.log(`Wrote ${entries.length} image dimensions to ${outFile}`);
