-- OPS-00: per-schedule cron health monitoring.
--
-- Monitored first wave:
--   * mux-sync-assets: every 4h + 2h grace
--   * dupr-sync-daily: every 24h + 2h grace
--   * DUPR rankings GitHub workflow: every 7d + 1d grace
--
-- pg_net responses are short-lived. The alert function calls
-- ops_refresh_cron_health_snapshot() every ten minutes; the function copies
-- the response fields into ops_cron_dispatches before pg_net garbage-collects
-- them. Browser roles have no access to any of these operational tables.

CREATE TABLE IF NOT EXISTS public.ops_cron_monitors (
  monitor_key               text PRIMARY KEY,
  display_name              text NOT NULL,
  source                    text NOT NULL CHECK (source IN ('pg_net', 'github_actions')),
  cron_job_name             text,
  external_identifier       text,
  expected_interval_seconds integer NOT NULL CHECK (expected_interval_seconds > 0),
  grace_seconds             integer NOT NULL CHECK (grace_seconds >= 0),
  monitoring_started_at     timestamptz NOT NULL DEFAULT now(),
  enabled                   boolean NOT NULL DEFAULT true,
  CHECK (
    (source = 'pg_net' AND cron_job_name IS NOT NULL) OR
    (source = 'github_actions' AND external_identifier IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS public.ops_cron_dispatches (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_key      text NOT NULL REFERENCES public.ops_cron_monitors(monitor_key) ON DELETE CASCADE,
  request_id       bigint NOT NULL,
  dispatched_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
  responded_at     timestamptz,
  http_status_code integer,
  timed_out        boolean,
  transport_error  text,
  response_content text,
  UNIQUE (monitor_key, request_id)
);

CREATE INDEX IF NOT EXISTS ops_cron_dispatches_monitor_dispatched_idx
  ON public.ops_cron_dispatches (monitor_key, dispatched_at DESC);

CREATE TABLE IF NOT EXISTS public.ops_cron_alert_state (
  monitor_key         text PRIMARY KEY REFERENCES public.ops_cron_monitors(monitor_key) ON DELETE CASCADE,
  last_state          text NOT NULL CHECK (last_state IN (
    'healthy', 'pending', 'never_ran', 'stale', 'ran_failed',
    'partial_success', 'caller_auth_failed'
  )),
  incident_started_at timestamptz,
  last_alerted_at     timestamptz,
  recovered_at        timestamptz,
  last_reason         text,
  updated_at          timestamptz NOT NULL DEFAULT now()
);

