-- Persist any available pg_net response, then return one row per configured
-- monitor. SECURITY DEFINER is required because cron/net schemas are not
-- exposed through PostgREST. Only service_role may execute it.
CREATE OR REPLACE FUNCTION public.ops_refresh_cron_health_snapshot()
RETURNS TABLE (
  monitor_key text,
  display_name text,
  source text,
  cron_job_name text,
  external_identifier text,
  expected_interval_seconds integer,
  grace_seconds integer,
  monitoring_started_at timestamptz,
  job_exists boolean,
  job_active boolean,
  scheduler_started_at timestamptz,
  scheduler_status text,
  scheduler_message text,
  dispatched_at timestamptz,
  responded_at timestamptz,
  http_status_code integer,
  timed_out boolean,
  transport_error text,
  response_content text,
  business_error_summary text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
BEGIN
  UPDATE public.ops_cron_dispatches AS dispatch
  SET
    responded_at = response.created,
    http_status_code = response.status_code,
    timed_out = response.timed_out,
    transport_error = response.error_msg,
    response_content = left(response.content, 10000)
  FROM net._http_response AS response
  WHERE response.id = dispatch.request_id
    AND dispatch.responded_at IS NULL;

  RETURN QUERY
  SELECT
    monitor.monitor_key,
    monitor.display_name,
    monitor.source,
    monitor.cron_job_name,
    monitor.external_identifier,
    monitor.expected_interval_seconds,
    monitor.grace_seconds,
    monitor.monitoring_started_at,
    (job.jobid IS NOT NULL) AS job_exists,
    job.active AS job_active,
    scheduler.start_time AS scheduler_started_at,
    scheduler.status AS scheduler_status,
    scheduler.return_message AS scheduler_message,
    dispatch.dispatched_at,
    dispatch.responded_at,
    dispatch.http_status_code,
    dispatch.timed_out,
    dispatch.transport_error,
    dispatch.response_content,
    business.error_summary AS business_error_summary
  FROM public.ops_cron_monitors AS monitor
  LEFT JOIN LATERAL (
    SELECT cron_job.jobid, cron_job.active
    FROM cron.job AS cron_job
    WHERE cron_job.jobname = monitor.cron_job_name
    LIMIT 1
  ) AS job ON true
  LEFT JOIN LATERAL (
    SELECT run.start_time, run.status, run.return_message
    FROM cron.job_run_details AS run
    WHERE run.jobid = job.jobid
    ORDER BY run.start_time DESC
    LIMIT 1
  ) AS scheduler ON true
  LEFT JOIN LATERAL (
    SELECT recorded.*
    FROM public.ops_cron_dispatches AS recorded
    WHERE recorded.monitor_key = monitor.monitor_key
    ORDER BY recorded.dispatched_at DESC
    LIMIT 1
  ) AS dispatch ON true
  LEFT JOIN LATERAL (
    SELECT sync_run.error_summary
    FROM public.dupr_sync_runs AS sync_run
    WHERE monitor.monitor_key = 'dupr-sync-daily'
      AND dispatch.dispatched_at IS NOT NULL
      AND sync_run.started_at BETWEEN
        dispatch.dispatched_at - interval '2 minutes'
        AND dispatch.dispatched_at + interval '30 minutes'
    ORDER BY abs(extract(epoch FROM sync_run.started_at - dispatch.dispatched_at))
    LIMIT 1
  ) AS business ON true
  WHERE monitor.enabled
  ORDER BY monitor.monitor_key;
END;
$function$;

REVOKE ALL ON FUNCTION public.ops_refresh_cron_health_snapshot() FROM PUBLIC;
