BEGIN;
SELECT plan(13);
SELECT ok(NOT EXISTS(SELECT 1 FROM pg_namespace n CROSS JOIN LATERAL aclexplode(n.nspacl) a WHERE n.nspname='public' AND a.grantee=0 AND a.privilege_type='CREATE'),'PUBLIC has no schema CREATE');
SELECT ok(NOT has_schema_privilege('anon','public','CREATE'),'anon cannot create public objects');
SELECT ok(NOT has_schema_privilege('authenticated','public','CREATE'),'member cannot create public objects');
SELECT ok(has_schema_privilege('anon','public','USAGE'),'anon schema usage preserved');
SELECT ok(has_schema_privilege('authenticated','public','USAGE'),'member schema usage preserved');
SELECT ok(has_schema_privilege('service_role','public','USAGE'),'service schema usage preserved');
SELECT ok(has_schema_privilege('service_role','public','CREATE'),'service DDL capability explicitly preserved');
SET LOCAL ROLE service_role;
SELECT lives_ok('CREATE TABLE public.qa_service_ddl_probe(id integer)','service role DDL remains available');
SELECT lives_ok('DROP TABLE public.qa_service_ddl_probe','service role cleanup works');
RESET ROLE;
SET LOCAL ROLE anon;
SELECT throws_ok('CREATE TABLE public.qa_anon_ddl_probe(id integer)','42501','permission denied for schema public','anon DDL actually denied');
RESET ROLE;
SET LOCAL ROLE authenticated;
SELECT throws_ok('CREATE TABLE public.qa_member_ddl_probe(id integer)','42501','permission denied for schema public','member DDL actually denied');
RESET ROLE;
SET LOCAL ROLE postgres;
SELECT lives_ok('CREATE TABLE public.qa_owner_ddl_probe(id integer)','migration owner DDL works');
SELECT lives_ok('DROP TABLE public.qa_owner_ddl_probe','migration owner cleanup works');
RESET ROLE;
SELECT * FROM finish();
ROLLBACK;
